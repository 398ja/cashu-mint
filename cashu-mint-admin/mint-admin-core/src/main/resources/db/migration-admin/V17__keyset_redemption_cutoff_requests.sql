-- cashu-mint#551: per-keyset redemption cutoff, requested and approved in mint-admin.
--
-- Retiring a keyset for redemption ends the holders' NUT-02 promise that an archived keyset
-- redeems indefinitely, so it is its own operation with its own approval: one Operator requests
-- a dated cutoff, a different Operator approves it, and only then does the outbox deliver it to
-- the mint. A request is never edited after it is decided. Moving a date is a new request.
CREATE TABLE keyset_redemption_cutoff_requests (
    request_id    UUID PRIMARY KEY,
    mint_id       UUID NOT NULL,
    keyset_id     VARCHAR(66) NOT NULL,
    redeem_until  TIMESTAMP WITH TIME ZONE NOT NULL,
    reason        TEXT NOT NULL,
    requested_by  VARCHAR(255) NOT NULL,
    requested_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    status        VARCHAR(32) NOT NULL,
    decided_by    VARCHAR(255),
    decided_at    TIMESTAMP WITH TIME ZONE,
    outcome       TEXT
);

CREATE INDEX idx_keyset_redemption_cutoff_requests_mint
    ON keyset_redemption_cutoff_requests (mint_id, requested_at);

-- Append-only: every step of every request, naming the Operator who took it.
CREATE TABLE keyset_redemption_cutoff_audit (
    entry_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id   UUID NOT NULL,
    mint_id      UUID NOT NULL,
    keyset_id    VARCHAR(66) NOT NULL,
    action       VARCHAR(64) NOT NULL,
    actor        VARCHAR(255) NOT NULL,
    occurred_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    detail       TEXT
);

CREATE INDEX idx_keyset_redemption_cutoff_audit_mint
    ON keyset_redemption_cutoff_audit (mint_id, occurred_at);
