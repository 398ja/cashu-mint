package xyz.tcheeric.cashu.mint.admin.rest.config;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.ArgumentMatchers.anyString;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.never;
import static org.mockito.Mockito.verify;
import static org.mockito.Mockito.when;

import java.security.SecureRandom;
import java.util.HexFormat;
import java.util.Map;
import java.util.concurrent.atomic.AtomicReference;

import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.ObjectProvider;
import org.springframework.vault.core.VaultTemplate;
import org.springframework.vault.core.VaultVersionedKeyValueOperations;
import org.springframework.vault.support.Versioned;

/**
 * mint-admin refuses to provision with a missing, weak or derivable seed (cashu-mint#545).
 *
 * <p>Every failure here must stop startup: the alternative is deriving keys without a secret.
 */
class VaultKeysetSeedSourceTest {

    private static final String MOUNT = "cashu";
    private static final String PATH = "seeds/mint-admin/keyset-master-seed";

    private static String randomHex() {
        final byte[] b = new byte[32];
        new SecureRandom().nextBytes(b);
        return HexFormat.of().formatHex(b);
    }

    /** A KV v2 mount holding at most one secret, honouring check-and-set version 0. */
    private static final class FakeKv {
        final AtomicReference<Map<String, Object>> stored = new AtomicReference<>();
        final VaultVersionedKeyValueOperations ops = mock(VaultVersionedKeyValueOperations.class);
        final VaultTemplate template = mock(VaultTemplate.class);

        FakeKv(final Map<String, Object> initial) {
            stored.set(initial);
            when(template.opsForVersionedKeyValue(MOUNT)).thenReturn(ops);
            when(ops.get(anyString())).thenAnswer(inv ->
                stored.get() == null ? null : Versioned.create(stored.get(), Versioned.Version.from(1)));
            when(ops.put(anyString(), any())).thenAnswer(inv -> {
                final Versioned<?> v = inv.getArgument(1);
                if (v.getVersion().isVersioned() || stored.get() != null) {
                    throw new IllegalStateException("check-and-set failed");
                }
                @SuppressWarnings("unchecked")
                final Map<String, Object> data = (Map<String, Object>) v.getData();
                stored.set(data);
                return null;
            });
        }
    }

    @Test
    @DisplayName("a strong seed in Vault is loaded")
    void loadsAStrongSeed() {
        final FakeKv kv = new FakeKv(Map.of("seed", randomHex()));
        final VaultKeysetSeedSource source = new VaultKeysetSeedSource(kv.template, MOUNT, PATH, false);
        assertThat(source.get().fingerprint()).hasSize(16);
        verify(kv.ops, never()).put(anyString(), any());
    }

    @Test
    @DisplayName("no seed in Vault: startup fails, and nothing is generated by default")
    void refusesWhenAbsent() {
        final FakeKv kv = new FakeKv(null);
        assertThatThrownBy(() -> new VaultKeysetSeedSource(kv.template, MOUNT, PATH, false))
            .isInstanceOf(IllegalStateException.class)
            .hasMessageContaining("refuses to provision");
        verify(kv.ops, never()).put(anyString(), any());
    }

    @Test
    @DisplayName("a weak seed in Vault fails startup, and its value is not echoed")
    void refusesAWeakSeed() {
        for (final String weak : new String[] {"00".repeat(32), "deadbeef".repeat(8), "abc", ""}) {
            final FakeKv kv = new FakeKv(Map.of("seed", weak));
            assertThatThrownBy(() -> new VaultKeysetSeedSource(kv.template, MOUNT, PATH, true))
                .isInstanceOf(IllegalStateException.class)
                .satisfies(e -> {
                    if (!weak.isEmpty()) {
                        assertThat(e.getMessage()).doesNotContain(weak);
                    }
                });
        }
    }

    @Test
    @DisplayName("a weak seed is never replaced by generate-if-absent")
    void generateNeverReplacesAnExistingSeed() {
        final FakeKv kv = new FakeKv(Map.of("seed", "00".repeat(32)));
        assertThatThrownBy(() -> new VaultKeysetSeedSource(kv.template, MOUNT, PATH, true))
            .isInstanceOf(IllegalStateException.class);
        verify(kv.ops, never()).put(anyString(), any());
    }

    @Test
    @DisplayName("generate-if-absent creates a seed with CAS 0 on an empty path, and the result is stable")
    void generatesOnceWhenAllowed() {
        final FakeKv kv = new FakeKv(null);
        final String first = new VaultKeysetSeedSource(kv.template, MOUNT, PATH, true).get().fingerprint();
        final String second = new VaultKeysetSeedSource(kv.template, MOUNT, PATH, true).get().fingerprint();
        assertThat(second).isEqualTo(first);
        verify(kv.ops, org.mockito.Mockito.times(1)).put(anyString(), any());
    }

    @Test
    @DisplayName("an unreadable Vault fails startup")
    void refusesWhenVaultUnreadable() {
        final FakeKv kv = new FakeKv(null);
        when(kv.ops.get(anyString())).thenThrow(new RuntimeException("permission denied"));
        assertThatThrownBy(() -> new VaultKeysetSeedSource(kv.template, MOUNT, PATH, true))
            .isInstanceOf(IllegalStateException.class);
    }

    @Test
    @DisplayName("no HashiCorp Vault configured: the seed bean refuses to start")
    void refusesWithoutVault() {
        @SuppressWarnings("unchecked")
        final ObjectProvider<VaultTemplate> none = mock(ObjectProvider.class);
        assertThatThrownBy(() -> new OutboxSchedulerConfiguration()
                .keysetMasterSeed(none, new org.springframework.mock.env.MockEnvironment(), MOUNT, PATH, true, false))
            .isInstanceOf(IllegalStateException.class)
            .hasMessageContaining("vault.hashi.enabled=false");
    }

    @Test
    @DisplayName("an ephemeral seed is refused outside the test profile")
    void ephemeralSeedNeedsTheTestProfile() {
        @SuppressWarnings("unchecked")
        final ObjectProvider<VaultTemplate> none = mock(ObjectProvider.class);
        final org.springframework.mock.env.MockEnvironment prod = new org.springframework.mock.env.MockEnvironment();
        prod.setActiveProfiles("prod");
        assertThatThrownBy(() -> new OutboxSchedulerConfiguration()
                .keysetMasterSeed(none, prod, MOUNT, PATH, false, true))
            .isInstanceOf(IllegalStateException.class)
            .hasMessageContaining("only allowed with the 'test'");

        final org.springframework.mock.env.MockEnvironment test = new org.springframework.mock.env.MockEnvironment();
        test.setActiveProfiles("test");
        assertThat(new OutboxSchedulerConfiguration()
                .keysetMasterSeed(none, test, MOUNT, PATH, false, true).get().fingerprint()).hasSize(16);
    }
}
